#!/bin/bash

# Cloud Run Deployment Script for AI Trip System Frontend
# This script deploys the Next.js application to Google Cloud Run

# Configuration
SERVICE_NAME="ai-trip-system-frontend"
REGION="us-central1"
PLATFORM="managed"
PORT=8080

# Resource Configuration
CPU=4
MEMORY="4Gi"
MIN_INSTANCES=1
MAX_INSTANCES=4
CONCURRENCY=80

# Build arguments from .env.production
# Make sure to update these values or source them from .env.production
NEXT_PUBLIC_API_BASE_URL="https://ai-trip-api-40205731279.us-central1.run.app/api/v1"
NEXT_PUBLIC_BOOKING_API_URL="https://booking-tour-api-40205731279.us-central1.run.app/api"
NEXT_PUBLIC_CHATBOT_SERVICE_URL="http://localhost:5000"
NEXT_PUBLIC_GOOGLE_PLACES_API_KEY="YOUR_GOOGLE_PLACES_API_KEY"
NEXT_PUBLIC_SUPABASE_URL="https://bvwritmmnhacndrxkvjn.supabase.co"
NEXT_PUBLIC_SUPABASE_ANON_KEY="YOUR_SUPABASE_ANON_KEY"
GOOGLE_CLIENT_ID="YOUR_GOOGLE_CLIENT_ID"
GOOGLE_CLIENT_SECRET="YOUR_GOOGLE_CLIENT_SECRET"
NEXTAUTH_SECRET="GROUP_2"

# The URL will be auto-generated by Cloud Run, update this after first deployment
NEXTAUTH_URL="https://${SERVICE_NAME}-40205731279.${REGION}.run.app"
NEXT_PUBLIC_APP_URL="https://${SERVICE_NAME}-40205731279.${REGION}.run.app"

echo "🚀 Deploying ${SERVICE_NAME} to Cloud Run..."
echo "📍 Region: ${REGION}"
echo "💻 CPU: ${CPU}, Memory: ${MEMORY}"
echo "📊 Min instances: ${MIN_INSTANCES}, Max instances: ${MAX_INSTANCES}"
echo ""

# Deploy to Cloud Run
gcloud run deploy ${SERVICE_NAME} \
  --source . \
  --region ${REGION} \
  --platform ${PLATFORM} \
  --allow-unauthenticated \
  --port ${PORT} \
  --cpu ${CPU} \
  --memory ${MEMORY} \
  --min-instances ${MIN_INSTANCES} \
  --max-instances ${MAX_INSTANCES} \
  --concurrency ${CONCURRENCY} \
  --set-build-env-vars "NEXT_PUBLIC_API_BASE_URL=${NEXT_PUBLIC_API_BASE_URL},NEXT_PUBLIC_BOOKING_API_URL=${NEXT_PUBLIC_BOOKING_API_URL},NEXT_PUBLIC_CHATBOT_SERVICE_URL=${NEXT_PUBLIC_CHATBOT_SERVICE_URL},NEXT_PUBLIC_GOOGLE_PLACES_API_KEY=${NEXT_PUBLIC_GOOGLE_PLACES_API_KEY},NEXT_PUBLIC_GOOGLE_API_KEY=${NEXT_PUBLIC_GOOGLE_PLACES_API_KEY},NEXT_PUBLIC_SUPABASE_URL=${NEXT_PUBLIC_SUPABASE_URL},NEXT_PUBLIC_SUPABASE_ANON_KEY=${NEXT_PUBLIC_SUPABASE_ANON_KEY},GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID},GOOGLE_CLIENT_SECRET=${GOOGLE_CLIENT_SECRET},NEXTAUTH_URL=${NEXTAUTH_URL},NEXTAUTH_SECRET=${NEXTAUTH_SECRET},NEXT_PUBLIC_APP_URL=${NEXT_PUBLIC_APP_URL}" \
  --set-env-vars "NEXT_PUBLIC_API_BASE_URL=${NEXT_PUBLIC_API_BASE_URL},NEXT_PUBLIC_BOOKING_API_URL=${NEXT_PUBLIC_BOOKING_API_URL},NEXT_PUBLIC_CHATBOT_SERVICE_URL=${NEXT_PUBLIC_CHATBOT_SERVICE_URL},NEXT_PUBLIC_GOOGLE_PLACES_API_KEY=${NEXT_PUBLIC_GOOGLE_PLACES_API_KEY},NEXT_PUBLIC_GOOGLE_API_KEY=${NEXT_PUBLIC_GOOGLE_PLACES_API_KEY},NEXT_PUBLIC_SUPABASE_URL=${NEXT_PUBLIC_SUPABASE_URL},NEXT_PUBLIC_SUPABASE_ANON_KEY=${NEXT_PUBLIC_SUPABASE_ANON_KEY},GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID},GOOGLE_CLIENT_SECRET=${GOOGLE_CLIENT_SECRET},NEXTAUTH_URL=${NEXTAUTH_URL},NEXTAUTH_SECRET=${NEXTAUTH_SECRET},NEXT_PUBLIC_APP_URL=${NEXT_PUBLIC_APP_URL}"

# Check deployment status
if [ $? -eq 0 ]; then
  echo ""
  echo "✅ Deployment successful!"
  echo "🌐 Your application URL: ${NEXTAUTH_URL}"
  echo ""
  echo "📝 Next steps:"
  echo "1. Update NEXTAUTH_URL and NEXT_PUBLIC_APP_URL with the actual Cloud Run URL"
  echo "2. Update Google OAuth redirect URIs to include your Cloud Run URL"
  echo "3. Test your application"
else
  echo ""
  echo "❌ Deployment failed. Please check the error messages above."
  exit 1
fi
