/**
 * Integration with FastAPI Trip Planner Backend
 * Connects Chatbot with the main AI Trip System database
 */

const TRIP_API_URL = process.env.TRIP_API_URL ||
  'https://ai-trip-api-40205731279.us-central1.run.app/api/v1';

export class TripAPIIntegration {

  /**
   * Create a new trip in the database
   * @param {Object} tripData - Trip information
   * @param {string} userToken - JWT token for authentication
   * @returns {Promise<Object>} Created trip object
   */
  async createTrip(tripData, userToken) {
    try {
      const response = await fetch(`${TRIP_API_URL}/trips/`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${userToken}`
        },
        body: JSON.stringify({
          name: tripData.name || `Trip to ${tripData.destination}`,
          description: tripData.description || 'Generated by AI Assistant',
          start_date: tripData.startDate,
          end_date: tripData.endDate,
          budget: tripData.budget,
          destination: tripData.destination
        })
      });

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      const result = await response.json();
      console.log('✅ Trip created:', result.id);
      return result;

    } catch (error) {
      console.error('❌ Create trip error:', error.message);
      return null;
    }
  }

  /**
   * Get AI recommendations for a trip
   * @param {number} tripId - Trip ID
   * @param {string} userToken - JWT token
   * @returns {Promise<Array>} List of recommendations
   */
  async getAIRecommendations(tripId, userToken) {
    try {
      const response = await fetch(
        `${TRIP_API_URL}/trips/${tripId}/ai-recommendations`,
        {
          headers: {
            'Authorization': `Bearer ${userToken}`
          }
        }
      );

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      return await response.json();

    } catch (error) {
      console.error('❌ Get recommendations error:', error.message);
      return [];
    }
  }

  /**
   * Create AI recommendation for a trip
   * @param {number} tripId - Trip ID
   * @param {string} recommendation - Recommendation text
   * @param {string} category - Category (itinerary, food, accommodation, etc.)
   * @param {string} userToken - JWT token
   * @returns {Promise<Object>} Created recommendation
   */
  async createAIRecommendation(tripId, recommendation, category, userToken) {
    try {
      const response = await fetch(
        `${TRIP_API_URL}/airecommendations/`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${userToken}`
          },
          body: JSON.stringify({
            trip_id: tripId,
            recommendation_text: recommendation,
            category: category || 'itinerary'
          })
        }
      );

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      const result = await response.json();
      console.log('✅ AI Recommendation saved:', result.id);
      return result;

    } catch (error) {
      console.error('❌ Create recommendation error:', error.message);
      return null;
    }
  }

  /**
   * Search for places matching query
   * @param {string} query - Search query
   * @param {string} userToken - JWT token
   * @returns {Promise<Array>} List of places
   */
  async searchPlaces(query, userToken) {
    try {
      const response = await fetch(
        `${TRIP_API_URL}/places/search?q=${encodeURIComponent(query)}`,
        {
          headers: {
            'Authorization': `Bearer ${userToken}`
          }
        }
      );

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      return await response.json();

    } catch (error) {
      console.error('❌ Search places error:', error.message);
      return [];
    }
  }

  /**
   * Add a place to trip itinerary
   * @param {number} tripId - Trip ID
   * @param {number} dayNumber - Day number in trip
   * @param {number} placeId - Place ID to add
   * @param {string} userToken - JWT token
   * @returns {Promise<Object>} Added trip place
   */
  async addPlaceToTrip(tripId, dayNumber, placeId, userToken) {
    try {
      const response = await fetch(
        `${TRIP_API_URL}/trip-places/`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${userToken}`
          },
          body: JSON.stringify({
            trip_id: tripId,
            day_number: dayNumber,
            place_id: placeId
          })
        }
      );

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      return await response.json();

    } catch (error) {
      console.error('❌ Add place to trip error:', error.message);
      return null;
    }
  }

  /**
   * Get trip details including all places
   * @param {number} tripId - Trip ID
   * @param {string} userToken - JWT token
   * @returns {Promise<Object>} Trip with places
   */
  async getTripDetails(tripId, userToken) {
    try {
      const response = await fetch(
        `${TRIP_API_URL}/trips/${tripId}`,
        {
          headers: {
            'Authorization': `Bearer ${userToken}`
          }
        }
      );

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}: ${response.statusText}`);
      }

      return await response.json();

    } catch (error) {
      console.error('❌ Get trip details error:', error.message);
      return null;
    }
  }

  /**
   * Health check for API connection
   * @returns {Promise<boolean>} True if API is accessible
   */
  async healthCheck() {
    try {
      const response = await fetch(`${TRIP_API_URL}/health`, {
        method: 'GET',
        timeout: 5000
      });

      return response.ok;
    } catch (error) {
      console.error('❌ API health check failed:', error.message);
      return false;
    }
  }
}

// Export singleton instance
export const tripAPI = new TripAPIIntegration();
